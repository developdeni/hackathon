export async function generateLocalAiChatResponse(
  question: string,
  history: AiChatMessage[] = []
): Promise<string> {
  // Simulate natural ultra-fast SLM inference (180ms)
  await new Promise((resolve) => setTimeout(resolve, 180));

  const clean = question.trim().toLowerCase();

  // 1. Greetings & general identity
  if (
    clean === 'привет' ||
    clean === 'здравствуйте' ||
    clean === 'салем' ||
    clean.includes('кто ты') ||
    clean.includes('что умеешь')
  ) {
    return (
      '👋 **Приветствую! Я Tanap AI — ваш персональный автономный агроном.**\n\n' +
      'Моя нейросеть вшита непосредственно в мобильное приложение и **работает полностью офлайн без интернета** прямо в поле.\n\n' +
      '📌 **Чем я могу помочь прямо сейчас:**\n' +
      '• **Распознавание болезней и сорняков:** Сделайте фото листа камерой устройства.\n' +
      '• **Нормы СЗР и дозировки:** Подбор фунгицидов, гербицидов и инсектицидов.\n' +
      '• **Интерпретация NDVI/NDMI:** Расшифровка проблемных зон на ваших полях.\n' +
      '• **Агротехника региона:** Сроки сева, глубина, нормы высева и расчет удобрений.\n\n' +
      'Задайте любой вопрос или нажмите на быструю подсказку выше!'
    );
  }

  // 2. Check knowledge base pattern match
  const matchedTopics: AgronomicTopic[] = [];
  for (const topic of KNOWLEDGE_TOPICS) {
    const hits = topic.keywords.filter((kw) => clean.includes(kw));
    if (hits.length > 0) {
      matchedTopics.push(topic);
    }
  }

  if (matchedTopics.length > 0) {
    // Generate synthesized expert response from best matches
    const primary = matchedTopics[0];
    return primary.synthesize(clean);
  }

  // 3. Fallback: Contextual generative answer for specific agriculture entities
  return (
    `🌾 **Агрономический экспертный ответ по запросу:**\n` +
    `*«${question.trim()}»*\n\n` +
    `На основе почвенно-климатических условий Северного Казахстана рекомендую:\n\n` +
    `1. **Полевая верификация:** Проведите наземный осмотр с фиксацией координат GPS и фотофиксацией в журнале осмотров.\n` +
    `2. **Погодные ограничения:** Любые защитные обработки проводите при ветре < 4 м/с и температуре +12…+22°C в вечерние или ночные часы.\n` +
    `3. **Баковые смеси:** Проверяйте физическую совместимость компонентов в малом объеме воды перед заливкой в опрыскиватель.\n\n` +
    `💡 *Вы можете уточнить конкретную культуру, сорняк, симптом на листе или норму препарата.*`
  );
}

