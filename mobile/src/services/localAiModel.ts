export async function loadSavedChatMessages(): Promise<AiChatMessage[]> {
  try {
    const raw = await AsyncStorage.getItem(STORAGE_KEY_CHAT);
    if (!raw) return [];
    return JSON.parse(raw) as AiChatMessage[];
  } catch {
    return [];
  }
}

export async function saveChatMessages(messages: AiChatMessage[]): Promise<void> {
  try {
    // Keep last 100 messages to prevent unbounded growth
    const trimmed = messages.slice(-100);
    await AsyncStorage.setItem(STORAGE_KEY_CHAT, JSON.stringify(trimmed));
  } catch {
    // Ignore storage failure
  }
}

export async function clearLocalChatHistory(): Promise<void> {
  try {
    await AsyncStorage.removeItem(STORAGE_KEY_CHAT);
  } catch {
    // Ignore
  }
}
